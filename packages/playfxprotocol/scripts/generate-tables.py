#!/usr/bin/env python3
"""Generates Sources/PlayFXProtocol/Tables.generated.swift from docs/protocol/data/*.hex.

Each table becomes one StaticString hex literal (compiled into the binary's read-only data) that is decoded
once, on first use. Run from anywhere: python3 packages/playfxprotocol/scripts/generate-tables.py
The SHA-256 of every table is checked by the tests against docs/protocol/rpcrypt.md section 3.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
data = root.parent.parent / "docs" / "protocol" / "data"
out = root / "Sources" / "PlayFXProtocol" / "Tables.generated.swift"


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


lines = [
    "// Generated by scripts/generate-tables.py from docs/protocol/data/*.hex. Do not edit.",
    "",
    "/// The constant tables of the RP crypt (docs/protocol/rpcrypt.md section 3), decoded once on first use.",
    "enum RPTables {",
]
for path in sorted(data.glob("*.hex")):
    text = "".join(path.read_text().split())
    assert re.fullmatch(r"[0-9a-f]+", text) and len(text) % 2 == 0, path.name
    lines.append(f"    /// `{path.name}`, {len(text) // 2} bytes.")
    lines.append(f'    static let {camel(path.stem)}: [UInt8] = decodeHexLiteral("{text}")')
    lines.append("")
lines[-1] = "}"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
